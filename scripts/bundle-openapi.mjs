import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import YAML from 'yaml'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceFile = resolve(projectRoot, 'openapi/openapi.yaml')
const outputFile = resolve(projectRoot, 'public/openapi.yaml')

const cache = new Map()

async function readYaml(file) {
  const absolute = resolve(file)
  if (!cache.has(absolute)) {
    cache.set(absolute, YAML.parse(await readFile(absolute, 'utf8')))
  }
  return cache.get(absolute)
}

function decodePointerPart(value) {
  return value.replaceAll('~1', '/').replaceAll('~0', '~')
}

function getByPointer(document, fragment) {
  if (!fragment || fragment === '#') return document

  const pointer = fragment.startsWith('#') ? fragment.slice(1) : fragment
  if (!pointer.startsWith('/')) {
    throw new Error(`Unsupported JSON pointer: ${fragment}`)
  }

  return pointer
    .slice(1)
    .split('/')
    .map(decodePointerPart)
    .reduce((value, key) => value[key], document)
}

async function resolveRef(ref, fromFile) {
  const hashIndex = ref.indexOf('#')
  const filePart = hashIndex === -1 ? ref : ref.slice(0, hashIndex)
  const fragment = hashIndex === -1 ? '' : ref.slice(hashIndex)
  const targetFile = filePart ? resolve(dirname(fromFile), filePart) : fromFile
  const document = await readYaml(targetFile)
  const value = getByPointer(document, fragment)

  if (value === undefined) {
    throw new Error(`Reference not found: ${ref} from ${fromFile}`)
  }

  return { value: structuredClone(value), file: targetFile }
}

function rewriteSchemaRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteSchemaRefs)
  if (!node || typeof node !== 'object') return node

  const result = {}

  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') {
      if (value.startsWith('#/')) {
        const name = value.split('/').at(-1)
        result[key] = `#/components/schemas/${name}`
        continue
      }

      if (value.includes('.yaml#/')) {
        const name = value.split('#/').at(-1)
        result[key] = `#/components/schemas/${name}`
        continue
      }
    }

    result[key] = rewriteSchemaRefs(value)
  }

  return result
}

async function bundle() {
  const root = structuredClone(await readYaml(sourceFile))

  for (const [path, pathRef] of Object.entries(root.paths ?? {})) {
    if (!pathRef?.$ref) continue
    const { value } = await resolveRef(pathRef.$ref, sourceFile)
    root.paths[path] = rewriteSchemaRefs(value)
  }

  for (const [name, schemaRef] of Object.entries(root.components?.schemas ?? {})) {
    if (!schemaRef?.$ref) continue
    const { value } = await resolveRef(schemaRef.$ref, sourceFile)
    root.components.schemas[name] = rewriteSchemaRefs(value)
  }

  for (const [name, securityRef] of Object.entries(root.components?.securitySchemes ?? {})) {
    if (!securityRef?.$ref) continue
    const { value } = await resolveRef(securityRef.$ref, sourceFile)
    root.components.securitySchemes[name] = value
  }

  const yaml = YAML.stringify(root, { lineWidth: 120 })
  await writeFile(
    outputFile,
    `# Generated from openapi/openapi.yaml. Do not edit this file manually.\n${yaml}`,
    'utf8',
  )

  console.log(`OpenAPI bundled: ${outputFile}`)
}

await bundle()
